/* Offline form verification. Synthetic responses are not participant feedback. */
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdirSync,readFileSync,writeFileSync} from 'node:fs';
import {dirname,join,resolve} from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'../..');
const output=join(root,'evidence/pilot-preparation-2026-10-04');
mkdirSync(output,{recursive:true});
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const browser=await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({viewport:{width:1280,height:900},acceptDownloads:true});
const checks=[],errors=[],network=[];
const formURL=pathToFileURL(join(root,'PILOT_FEEDBACK.html')).href;
const page=await context.newPage();
page.on('pageerror',error=>errors.push(error.name));
page.on('request',request=>{if(/^https?:/.test(request.url()))network.push('external_request');});
await context.route('**/*',route=>/^https?:/.test(route.request().url())?route.abort():route.continue());
try{
  await page.goto(formURL);
  await page.getByRole('heading',{name:'What could you complete?'}).waitFor();
  assert.equal(await page.locator('#tasks select').count(),9);
  assert.equal(await page.locator('#ratings select').count(),4);
  checks.push('Nine tasks and four ratings rendered offline');
  await page.getByRole('button',{name:'Export feedback file'}).click();
  assert.equal(await page.locator('#feedback').evaluate(form=>form.checkValidity()),false);
  assert.equal(await page.locator('#status').textContent(),'');
  checks.push('Required unanswered fields block export');
  await page.keyboard.press('Escape');
  await page.evaluate(()=>{document.activeElement.blur();window.scrollTo(0,0);});
  await page.screenshot({path:join(output,'desktop-blank-form.png')});
  await page.setViewportSize({width:320,height:720});
  let size=await page.evaluate(()=>({width:document.documentElement.clientWidth,scroll:document.documentElement.scrollWidth}));
  assert.equal(size.width,320);assert.ok(size.scroll<=size.width);
  await page.screenshot({path:join(output,'mobile-blank-form.png')});
  await page.getByRole('heading',{name:'What could you complete?'}).scrollIntoViewIfNeeded();
  await page.screenshot({path:join(output,'mobile-task-outcomes.png')});
  checks.push('320px form and task controls fit the document width');
  await page.getByLabel('Participant ID *',{exact:true}).selectOption('P01');
  await page.getByLabel('Session date *',{exact:true}).fill('2026-10-04');
  await page.getByLabel('Device/window used *',{exact:true}).selectOption('both-windows');
  await page.getByLabel('Approximate total minutes',{exact:true}).fill('20');
  await page.getByLabel('What was hardest or confusing?',{exact:true}).fill('Synthetic form-check fixture only; no student participated.');
  for(const select of await page.locator('#tasks select').all())await select.selectOption('unaided');
  await page.locator('#task_mobile').selectOption('not_attempted');
  for(const select of await page.locator('#ratings select').all())await select.selectOption('4');
  await page.locator('#rating_relevance').selectOption('not_observed');
  const pendingDownload=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export feedback file'}).click();
  const download=await pendingDownload;
  assert.equal(download.suggestedFilename(),'professor-finder-pilot-P01-2026-10-04.json');
  const payload=JSON.parse(readFileSync(await download.path(),'utf8'));
  assert.equal(payload.participant_id,'P01');assert.equal(payload.minutes,20);
  assert.equal(payload.task_mobile,'not_attempted');assert.equal(payload.rating_relevance,'not_observed');
  assert.ok(payload.confusion.startsWith('Synthetic form-check'));
  checks.push('Export downloads valid JSON with typed minutes and correct ID/date filename');
  checks.push('Not-attempted and not-observed answers preserved without success conversion');
  assert.equal(await page.evaluate(()=>localStorage.length),0);
  assert.equal(network.length,0);assert.equal(errors.length,0);
  checks.push('No network requests, automatic local storage, or uncaught page errors');
}finally{
  writeFileSync(join(output,'form-checks.json'),JSON.stringify({passed_checks:checks,errors,network_requests:network.length,real_participants:0,synthetic_export_retained:false,visual_review:'Pending screenshot inspection'},null,2));
  await browser.close();
}
console.log(JSON.stringify({passed:checks.length,real_participants:0}));
